async function recordAuthActivity(eventType) {
  if (!session?.user?.id || !["login","logout"].includes(eventType)) return;
  try { await sb.rpc("record_auth_activity", { p_event_type: eventType, p_user_agent: navigator.userAgent || null }); } catch (_) {}
}

// supabase-js also emits SIGNED_IN whenever a tab regains focus with an already-valid
// session. Treating that as a fresh login re-ran the whole auth sequence (/auth/v1/user,
// role sync, consent check, profile + vendor reload...) on every tab switch. Decide once
// here whether it is a genuinely new sign-in; the other listeners reuse the decision.
window.__levroSignInIsNew = () => !(window.__signInDecision && Date.now() - window.__signInDecision.at < 3000 && window.__signInDecision.isNew === false);
sb.auth.onAuthStateChange((_event, _sess) => {
  try { window.__lvOnAuthChange && window.__lvOnAuthChange(_event, _sess); } catch (_) {}
  if (_event === "SIGNED_IN") {
    const same = !!(session?.user?.id && _sess?.user?.id === session.user.id && profile);
    window.__signInDecision = { at: Date.now(), isNew: !same };
    if (same) return;
  }
  if (_event === "PASSWORD_RECOVERY") {
    hideLogin();
    isVoluntaryPasswordChange = false;
    manualResetMode = false;
    byId("currentPasswordWrap").classList.add("hidden");
    byId("confirmNewPasswordWrap").classList.add("hidden");
    byId("resetPasswordTitle").innerHTML = '<i class="fa-solid fa-key"></i> Set a new password';
    byId("newPasswordInput").value = "";
    byId("confirmNewPasswordInput").value = "";
    byId("resetPasswordError").classList.add("hidden");
    byId("resetPasswordModal").classList.remove("hidden");
    return;
  }
  if (_event === "SIGNED_OUT" && session && !manualLogout) {
    // Not a log-out the person asked for. Another open tab or the installed app may have just renewed the login, so
    // check once before signing them out in the middle of what they are doing.
    const stillIn = session;
    setTimeout(async () => {
      try {
        const { data } = await sb.auth.getSession();
        if (data?.session) { session = data.session; return; }
      } catch (_) {}
      if (session === stillIn || !session) { showToast("You've been signed out. Please sign in again.", "error"); manualLogout = false; refreshAuthStateOnce(); }
    }, 1500);
    return;
  }
  // Covers Google sign-in too -- that flow is a full-page redirect away and
  // back, so it never runs through submitAuth()'s own explicit call. SIGNED_IN
  // only fires for an actual new authentication (password, OAuth, magic
  // link), never for a plain page reload restoring an existing session
  // (that's INITIAL_SESSION), so this can't log someone out of their own tab.
  manualLogout = false;
  refreshAuthStateOnce();
});

