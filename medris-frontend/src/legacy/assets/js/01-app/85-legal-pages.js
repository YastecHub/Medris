async function checkManualResetStatus() {
  const raw = localStorage.getItem("levromart_manual_password_reset");
  if (!raw) return null;
  let state;
  try { state = JSON.parse(raw); } catch (_) { localStorage.removeItem("levromart_manual_password_reset"); return null; }
  if (!state?.request_id || !state?.token) return null;
  try {
    const { data, error } = await sb.rpc("get_manual_password_reset_status", {
      p_request_id: state.request_id,
      p_token: state.token
    });
    if (error) throw error;
    if (data?.status === "approved") {
      openApprovedManualReset(state.email || data.email || "");
    } else if (data?.status === "rejected" || data?.status === "expired" || data?.status === "invalid") {
      stopManualResetWatcher();
      localStorage.removeItem("levromart_manual_password_reset");
      closeManualResetWaiting();
      if (data?.status === "rejected") showToast("Your password reset request was rejected by the admin.", "error");
      else if (data?.status === "expired") showToast("Your password reset request expired. Please submit a new request.", "error");
    } else if (data?.status === "pending") {
      if (!byId("manualResetWaitingModal")?.classList.contains("hidden")) {
        byId("manualResetWaitingStatus").textContent = "Waiting for admin approval";
      } else {
        showManualResetWaiting(state.email || data.email || "");
      }
    }
    return data;
  } catch (e) {
    console.warn("Manual password reset status check failed", e);
    return null;
  }
}

function startManualResetWatcher() {
  stopManualResetWatcher();
  checkManualResetStatus();
  manualResetWatcherTimer = setInterval(()=>{ if(!document.hidden) checkManualResetStatus(); }, 6000);
}

function resumeManualResetWatcher() {
  const raw = localStorage.getItem("levromart_manual_password_reset");
  if (!raw) return;
  try {
    const state = JSON.parse(raw);
    if (state?.request_id && state?.token) {
      showManualResetWaiting(state.email || "");
      startManualResetWatcher();
    }
  } catch (_) {
    localStorage.removeItem("levromart_manual_password_reset");
  }
}

async function submitNewPassword() {
  const password = byId("newPasswordInput").value;
  const errorEl = byId("resetPasswordError");
  errorEl.classList.add("hidden");
  if (!password || password.length < 8) { errorEl.textContent = "Password must be at least 8 characters."; errorEl.classList.remove("hidden"); return; }
  if (manualResetMode) {
    const confirmation = byId("confirmNewPasswordInput").value;
    if (password !== confirmation) { errorEl.textContent = "Passwords do not match."; errorEl.classList.remove("hidden"); return; }
    const raw = localStorage.getItem("levromart_manual_password_reset");
    let state = null;
    try { state = JSON.parse(raw || ""); } catch (_) {}
    if (!state?.request_id || !state?.token || !state?.email) {
      errorEl.textContent = "This reset request is no longer available. Please submit a new request.";
      errorEl.classList.remove("hidden");
      return;
    }
    const btn = byId("resetPasswordSubmit");
    btn.disabled = true;
    try {
      const { error } = await sb.rpc("complete_manual_password_reset", {
        p_request_id: state.request_id,
        p_token: state.token,
        p_new_password: password
      });
      if (error) throw error;
      const { error: signInError } = await sb.auth.signInWithPassword({ email: state.email, password });
      if (signInError) throw signInError;
      localStorage.removeItem("levromart_manual_password_reset");
      stopManualResetWatcher();
      manualResetMode = false;
      byId("confirmNewPasswordWrap").classList.add("hidden");
      byId("resetPasswordModal").classList.add("hidden");
      showToast("Password updated successfully.", "success");
      await refreshAuthStateOnce();
      navigate("home", {}, false);
    } catch (err) {
      errorEl.textContent = err.message || "Could not set the new password.";
      errorEl.classList.remove("hidden");
    } finally {
      btn.disabled = false;
    }
    return;
  }
  const btn = byId("resetPasswordSubmit");
  btn.disabled = true;
  try {
    // Voluntary changes (already logged in, from Settings) must prove they
    // know the current password first - re-authenticating with it is the
    // standard way to do that with Supabase Auth, since there's no separate
    // "verify password" call. The forced PASSWORD_RECOVERY flow (from the
    // emailed reset link) skips this - the email link itself is the proof.
    if (isVoluntaryPasswordChange) {
      const currentPassword = byId("currentPasswordInput").value;
      if (!currentPassword) { errorEl.textContent = "Enter your current password."; errorEl.classList.remove("hidden"); btn.disabled = false; return; }
      const { error: reauthError } = await sb.auth.signInWithPassword({ email: session.user.email, password: currentPassword });
      if (reauthError) { errorEl.textContent = "Current password is incorrect."; errorEl.classList.remove("hidden"); btn.disabled = false; return; }
    }
    const { error } = await sb.auth.updateUser({ password });
    if (error) throw error;
    byId("resetPasswordModal").classList.add("hidden");
    isVoluntaryPasswordChange = false;
    showToast("Password updated. You're logged in.", "success");
    await refreshAuthStateOnce();
    history.replaceState({ view: "home", params: {} }, "", location.pathname);
    navigate("home", {}, false);
  } catch (err) {
    errorEl.textContent = err.message;
    errorEl.classList.remove("hidden");
  } finally {
    btn.disabled = false;
  }
}

