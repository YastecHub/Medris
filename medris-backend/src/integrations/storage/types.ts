/**
 * Provider-independent file storage.
 *
 * Levromart keeps public images (product photos, avatars, logos, carousel) on
 * Cloudflare R2 and private files (verification documents, chat/support
 * attachments, receipts, dispute evidence) in Supabase Storage behind signed
 * URLs. Cloudinary is available as a third adapter for images. Code that
 * stores files depends on this interface, not on a provider, so moving a
 * folder between providers is a configuration and data-copy task.
 */

export type StorageProvider = "r2" | "supabase" | "cloudinary";

export interface DirectUpload {
  /** Where the browser sends the file. */
  uploadUrl: string;
  method: "PUT" | "POST";
  /** Form fields (POST uploads) or headers (PUT uploads) the browser must include. */
  fields?: Record<string, string>;
  headers?: Record<string, string>;
  /** Where the file will be readable once uploaded (public folders only). */
  publicUrl?: string;
  expiresInSeconds: number;
}

export interface ObjectStorage {
  readonly provider: StorageProvider;
  /** A short-lived, single-object upload the browser can perform directly. */
  createDirectUpload(key: string, contentType: string): Promise<DirectUpload>;
  /** Server-side upload. */
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  /** Public URL for public folders. */
  publicUrl(key: string): string;
  remove(keys: string[]): Promise<void>;
  /** Keys under a prefix (non-recursive where the provider is). */
  list(prefix: string): Promise<string[]>;
}

/** Keys are generated by the server or validated: no traversal, no absolute paths, no control characters. */
export function assertSafeKey(key: string): void {
  // eslint-disable-next-line no-control-regex -- rejecting control characters is the point
  if (!key || key.length > 512 || /\.\.|\/\/|^\/|[\0-\x1f\\]/.test(key)) throw new Error("Invalid storage key.");
}
